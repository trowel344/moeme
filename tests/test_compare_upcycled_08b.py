def test_summarise_prompt_marks_identical_output():
    row = cmp08b.summarise_prompt("p", [1, 2], [1, 2],
                                  {"dense": "a", "moe": "a"})
    assert row["identical"] is True
    assert row["first_divergence_index"] is None
    assert row["token_match_fraction"] == 1.0
    assert row["tokens_compared"] == 2


def test_summarise_prompt_keeps_both_texts_when_they_differ():
    row = cmp08b.summarise_prompt("p", [1, 2, 3], [1, 9, 3],
                                  {"dense": "Paris", "moe": "the world"})
    assert row["identical"] is False
    assert row["first_divergence_index"] == 1
    assert row["dense_text"] == "Paris"
    assert row["moe_text"] == "the world"


def test_summarise_prompt_carries_the_prompt_verbatim():
    """The report is read after the fact; a row whose prompt drifted out of step
    with the text under it is unreadable."""
    row = cmp08b.summarise_prompt("def f():\n    ", [1], [1],
                                  {"dense": "a", "moe": "a"})
    assert row["prompt"] == "def f():\n    "


