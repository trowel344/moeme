"""The dense-vs-upcycled comparison's own logic.

`experiments/compare_upcycled_08b.py` answers a question the PoC's perplexity
ratio cannot: does the upcycled model still *behave* like the stock one? Its
answer rests on pieces that are pure functions, so they are testable on the CPU
with no download, no GPU and no network:

  * how two token sequences are compared (a divergence index, an agreement
    fraction) -- the numbers the report quotes;
  * the greedy decode loop, which must pick the argmax and nothing else;
  * the distinction between the **dense-limit control** and the **trained
    all-experts figure**. Measured on a fresh partition, `top_k = n_experts` is
    the dense layer and reproduces dense perplexity (rel. error 3.7e-04 on the
    real run); measured on the trained partition it is 82x dense. Only the first
    is a correctness check, and reading the second as a broken control would
    discard a real finding, so the names and the docstring pin the difference.
"""

from __future__ import annotations

import os
import sys

import pytest
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "src"))
sys.path.insert(0, os.path.join(HERE, "..", "experiments"))

import compare_upcycled_08b as cmp08b          # noqa: E402


# ---------------------------------------------------------------------------
# sequence comparison
# ---------------------------------------------------------------------------

def test_first_divergence_finds_the_first_differing_index():
    assert cmp08b.first_divergence([1, 2, 3, 4], [1, 2, 9, 4]) == 2


def test_first_divergence_at_token_zero():
    assert cmp08b.first_divergence([1, 2, 3], [7, 2, 3]) == 0


def test_identical_sequences_have_no_divergence():
    assert cmp08b.first_divergence([1, 2, 3], [1, 2, 3]) is None


def test_a_prefix_is_not_a_divergence():
    """A shorter sequence that agrees everywhere it exists has not diverged.
    Returning the end of it would overstate the difference between a model that
    stopped early and one that said something else."""
    assert cmp08b.first_divergence([1, 2], [1, 2, 3, 4]) is None
    assert cmp08b.first_divergence([1, 2, 3, 4], [1, 2]) is None


def test_match_fraction_counts_positional_agreement():
    assert cmp08b.match_fraction([1, 2, 3, 4], [1, 2, 9, 4]) == pytest.approx(0.75)
    assert cmp08b.match_fraction([5, 5], [5, 5]) == 1.0
    assert cmp08b.match_fraction([5, 5], [6, 6]) == 0.0


def test_match_fraction_compares_only_the_shorter_length():
    """Positions past the shorter sequence were never generated by both models,
    so they cannot count as either agreement or disagreement."""
    assert cmp08b.match_fraction([1, 2], [1, 2, 99, 99]) == 1.0


def test_match_fraction_of_two_empty_sequences_is_one():
    """Two empty sequences are identical. Returning 0.0 would make a model that
    generated nothing look maximally different from one that generated nothing."""
    assert cmp08b.match_fraction([], []) == 1.0


