def test_docstring_keeps_the_two_all_experts_numbers_apart():
    """The distinction is the easiest thing in this file to get backwards, and
    the whole report depends on it, so it is pinned in prose."""
    doc = cmp08b.__doc__
    assert "fresh" in doc and "trained" in doc
    assert "not a control" in doc


def test_report_field_names_stay_distinct(monkeypatch, tmp_path):
    """The report must not be able to hold one number under both meanings."""
    src = open(cmp08b.__file__).read()
    assert '"dense_limit_val_ppl"' in src
    assert '"trained_all_experts_val_ppl"' in src
    # the control is measured before the checkpoint is loaded; if this ordering
    # ever flips, the control silently stops testing the partition plumbing
    i_fresh = src.index('saved = set_topk(args.experts)')
    i_load = src.index('state = torch.load(args.ckpt')
    assert i_fresh < i_load, \
        "the dense-limit control must be measured on the fresh partition"


def test_report_carries_the_checkpoint_provenance_check():
    """The trained perplexity does not reproduce the recorded run's exactly, so
    the report has to say whether that is a different model or the same model
    evaluated twice. That is answered by recomputing the per-layer residuals on
    the loaded weights and by matching against the recording run's step count --
    a run that stopped early is not the run the checkpoint came from."""
    src = open(cmp08b.__file__).read()
    assert '"metrics_trained"' in src
    assert '"recorded_run"' in src
    assert 'poc.capture_reference(' in src
    assert 'poc.evaluate_layers(' in src
    assert 'steps_completed") != state["step"]' in src, \
        "the provenance match must check the step count, not only the config"
