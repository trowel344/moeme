def test_prompt_set_is_non_empty_and_stable():
    assert len(cmp08b.PROMPTS) >= 4
    assert all(isinstance(p, str) and p for p in cmp08b.PROMPTS)
    assert len(set(cmp08b.PROMPTS)) == len(cmp08b.PROMPTS), "duplicate prompts"
    # a prompt set that moves between runs cannot be compared to a previous run
    assert cmp08b.PROMPTS[0] == "The capital of France is"


# ---------------------------------------------------------------------------
# the greedy loop
# ---------------------------------------------------------------------------

class _TableLM:
    """A model whose next-token distribution is a fixed function of the last
    token. Greedy decoding is then fully determined, so the loop can be checked
    without a download."""

    def __init__(self, nxt: dict[int, int], vocab: int = 8):
        self.nxt, self.vocab = nxt, vocab

    def __call__(self, ids):
        out = ids.new_zeros((ids.shape[0], ids.shape[1], self.vocab),
                            dtype=torch.float32)
        for b in range(ids.shape[0]):
            target = self.nxt.get(int(ids[b, -1]), 0)
            out[b, -1, target] = 5.0
        from types import SimpleNamespace
        return SimpleNamespace(logits=out)


def test_greedy_ids_picks_the_argmax_each_step():
    lm = _TableLM({1: 2, 2: 3, 3: 4})
    ids = torch.tensor([[1]])
    assert cmp08b.greedy_ids(lm, ids, 3) == [2, 3, 4]


def test_greedy_ids_stops_at_the_requested_length():
    lm = _TableLM({1: 2, 2: 2})
    assert cmp08b.greedy_ids(lm, torch.tensor([[1]]), 5) == [2, 2, 2, 2, 2]


def test_greedy_ids_returns_only_the_new_tokens():
    """The prompt is context, not output: including it would inflate agreement
    between two models that were handed the same prompt."""
    lm = _TableLM({1: 2, 2: 3})
    out = cmp08b.greedy_ids(lm, torch.tensor([[9, 9, 1]]), 2)
    assert out == [2, 3]
    assert len(out) == 2


